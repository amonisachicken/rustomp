//! 代码发射：`identity.rs` / `params.rs` / `plugin_impl.rs` / `mod.rs`。
//!
//! 三条硬规则：
//! 1. **确定性**：同一份 manifest 永远产出同样的字节（可以直接入库 + `--check`）；
//! 2. **可读**：生成物是给人看的 Rust，不是机器码 —— 要能 review；
//! 3. **不猜**：manifest 里没写的东西不编造（缺 `[ui]` 就不生成 GUI 代码）。

use crate::manifest::{Manifest, ParamFormat, ParamKind};

const HEADER: &str = "// @generated by rustomp-gen — do not edit\n\
// 手改请改 rustomp.toml 后重新生成；一次性改动放进同目录的 local.rs。\n";

fn rust_str(s: &str) -> String {
    // 只处理常见转义；manifest 里的字符串不会含控制字符
    let escaped = s.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

fn fmt_f64(v: f64) -> String {
    // 去掉浮点噪声，保证输出稳定
    let s = format!("{v:?}");
    if s.contains('.') || s.contains('e') {
        s
    } else {
        format!("{s}.0")
    }
}

// ---------------------------------------------------------------- identity.rs

/// 身份常量。变体（mono/stereo/dual）全部用 `cfg` 选择 —— 于是这个文件是**静态**的，
/// 不再需要 build.rs 按 feature 重新生成。
pub fn identity_rs(m: &Manifest) -> String {
    let mut out = String::from(HEADER);
    out.push_str("// 身份与元数据。变体差异用 cfg 选择。\n");
    // 按变体分叉的常量在某些 feature 组合下不会被用到，属正常
    out.push_str("#![allow(dead_code)]\n\n");

    let variants = m.variants();
    let mut emit_variant = |suffix: &dyn Fn(&str) -> String| {
        for v in &variants {
            let cfg = cfg_for(v);
            out.push_str(&format!("{cfg}\n{}\n\n", suffix(v)));
        }
        // 兜底：没有任何 feature 时用 dual
        out.push_str(&format!(
            "#[cfg(not(any({})))]\n{}\n\n",
            variants_cfg_any(&variants),
            suffix("dual")
        ));
    };

    // NAME / CLAP_ID / VST3_ID 需要按变体分叉
    emit_variant(&|v| {
        let (name_suffix, _) = Manifest::variant_suffix(v);
        format!(
            "pub const META_NAME: &str = {};",
            rust_str(&format!("{}{name_suffix}", m.plugin.name))
        )
    });
    emit_variant(&|v| {
        let (_, id_suffix) = Manifest::variant_suffix(v);
        format!(
            "pub const META_CLAP_ID: &str = {};",
            rust_str(&format!("{}{id_suffix}", m.plugin.clap_id))
        )
    });
    emit_variant(&|v| {
        let id = m.vst3_id(v);
        format!("pub const META_VST3_ID: [u8; 16] = *b{};", rust_str(id))
    });

    // 其余与变体无关
    out.push_str(&format!(
        "pub const META_VENDOR: &str = {};\n",
        rust_str(&m.plugin.vendor)
    ));
    out.push_str(&format!(
        "pub const META_URL: &str = {};\n",
        rust_str(&m.plugin.url)
    ));
    out.push_str(&format!(
        "pub const META_EMAIL: &str = {};\n",
        rust_str(&m.plugin.email)
    ));
    out.push_str(&format!(
        "pub const META_DESCRIPTION: &str = {};\n",
        rust_str(&m.plugin.description)
    ));
    out.push_str(&format!(
        "pub const META_CLAP_DESCRIPTION: Option<&str> = Some(META_DESCRIPTION);\n"
    ));
    out.push_str(&format!(
        "/// 变体名（用于日志/调试）：{}\npub const META_VARIANT: &str = {};\n",
        variants.join(" / "),
        // 运行时不可知，给个 cfg 选择
        "VARIANT_NAME"
    ));
    out.push_str(&format!(
        "#[cfg(feature = \"mono\")]\npub const VARIANT_NAME: &str = \"mono\";\n\
         #[cfg(feature = \"stereo\")]\npub const VARIANT_NAME: &str = \"stereo\";\n\
         #[cfg(not(any(feature = \"mono\", feature = \"stereo\")))]\npub const VARIANT_NAME: &str = \"dual\";\n"
    ));
    out
}

fn cfg_for(variant: &str) -> String {
    match variant {
        "mono" | "stereo" => format!("#[cfg(feature = \"{variant}\")]"),
        _ => "#[cfg(not(any(feature = \"mono\", feature = \"stereo\")))]".to_string(),
    }
}

fn variants_cfg_any(variants: &[String]) -> String {
    variants
        .iter()
        .filter(|v| v.as_str() != "dual")
        .map(|v| format!("feature = \"{v}\""))
        .collect::<Vec<_>>()
        .join(", ")
}

// ---------------------------------------------------------------- params.rs

pub fn params_rs(m: &Manifest) -> String {
    let mut out = String::from(HEADER);
    out.push_str("// 参数表（由 rustomp.toml 的 [[params]] 生成）。\n\n");
    out.push_str("use nih_plug::prelude::*;\n");
    if m.build.gui {
        out.push_str("use std::sync::Arc;\n");
    }
    out.push_str("\n");

    out.push_str("#[derive(Params)]\npub struct PluginParams {\n");
    for p in &m.params {
        out.push_str(&format!("    /// {}\n", p.name));
        out.push_str(&format!("    #[id = \"{}\"]\n", p.id));
        let ty = match p.kind {
            ParamKind::Float => "FloatParam",
            ParamKind::Bool => "BoolParam",
        };
        out.push_str(&format!("    pub {}: {},\n\n", p.id, ty));
    }
    if m.build.gui {
        // 窗口尺寸记忆（nih-plug 的 #[persist]）
        out.push_str("    #[persist = \"editor-state\"]\n    pub editor_state: Arc<::nih_plug_egui::EguiState>,\n\n");
    }
    out.push_str("}\n\n");

    // Default
    out.push_str("impl Default for PluginParams {\n    fn default() -> Self {\n        Self {\n");
    for p in &m.params {
        out.push_str(&format!("            {},\n", default_expr(p)));
    }
    if m.build.gui {
        let (w, h) = m.window_size();
        out.push_str(&format!(
            "            editor_state: ::nih_plug_egui::EguiState::from_size({w}, {h}),\n"
        ));
    }
    out.push_str("        }\n    }\n}\n\n");

    // 拍快照：只含带 circuit 映射的参数
    let dsp = m.dsp_params();
    out.push_str("impl PluginParams {\n");
    out.push_str("    /// 取出电路参数（**平滑后的值**；每样本调用）。\n");
    out.push_str(&format!(
        "    pub fn to_dsp(&self) -> {}::{} {{\n",
        m.circuit_crate(),
        m.circuit.params_type
    ));
    if !m.circuit.params_builder.is_empty() {
        // 构造函数模式：按 manifest 顺序把所有参数按值传进去
        // （float 用平滑值、bool 直接取），由电路 crate 决定怎么组装。
        let args: Vec<String> = m
            .params
            .iter()
            // `bypass` 是**保留 id**：由引擎的 true-bypass 处理，不进电路参数
            .filter(|p| p.id != "bypass")
            .map(|p| match p.kind {
                ParamKind::Float => format!("self.{}.smoothed.next() as f64", p.id),
                ParamKind::Bool => format!("self.{}.value()", p.id),
            })
            .collect();
        out.push_str(&format!(
            "        {}::{}({})\n",
            m.circuit_crate(),
            m.circuit.params_builder,
            args.join(", ")
        ));
    } else if dsp.is_empty() {
        out.push_str(&format!(
            "        {}::{}::default()\n",
            m.circuit_crate(),
            m.circuit.params_type
        ));
    } else {
        out.push_str(&format!(
            "        {}::{} {{\n",
            m.circuit_crate(),
            m.circuit.params_type
        ));
        for p in &dsp {
            let field = p.circuit.as_deref().unwrap_or("");
            let expr = match p.kind {
                // 电位器位置 0..1 直接作为电路参数（taper 在电路里换算）
                ParamKind::Float => format!("self.{}.smoothed.next() as f64", p.id),
                ParamKind::Bool => format!("self.{}.value()", p.id),
            };
            out.push_str(&format!("            {field}: {expr},\n"));
        }
        out.push_str("        }\n");
    }
    out.push_str("    }\n}\n");
    out
}

fn default_expr(p: &crate::manifest::ParamMeta) -> String {
    match p.kind {
        ParamKind::Float => {
            let default = p.default.as_ref().and_then(|v| v.as_float()).unwrap_or(0.5);
            let range = p.range.unwrap_or([0.0, 1.0]);
            let smoothing = p.smoothing_ms.unwrap_or(20.0);
            let format = p.format.unwrap_or(ParamFormat::Percent);
            let mut s = format!(
                "{}: FloatParam::new({}, {},\n                FloatRange::Linear {{ min: {}, max: {} }})\n                .with_smoother(SmoothingStyle::Linear({}))",
                p.id,
                rust_str(&p.name),
                fmt_f64(default),
                fmt_f64(range[0]),
                fmt_f64(range[1]),
                fmt_f64(smoothing),
            );
            s.push_str(&match format {
                ParamFormat::Percent => {
                    "\n                .with_unit(\" %\")\n                .with_value_to_string(formatters::v2s_f32_percentage(0))\n                .with_string_to_value(formatters::s2v_f32_percentage())"
                }
                ParamFormat::Db => {
                    "\n                .with_unit(\" dB\")\n                .with_value_to_string(formatters::v2s_f32_gain_to_db(1))\n                .with_string_to_value(formatters::s2v_f32_gain_to_db())"
                }
                ParamFormat::Plain | ParamFormat::Enum => {
                    "\n                .with_step_size(0.01)"
                }
            });
            s
        }
        ParamKind::Bool => {
            let default = p
                .default
                .as_ref()
                .and_then(|v| v.as_bool())
                .unwrap_or(false);
            format!(
                "{}: BoolParam::new({}, {})",
                p.id,
                rust_str(&p.name),
                default
            )
        }
    }
}

// ---------------------------------------------------------------- plugin_impl.rs

pub fn plugin_impl_rs(m: &Manifest) -> String {
    let s = m.struct_name();
    let circ = &m.circuit.plugin_type;
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "// 插件实现（由 rustomp.toml 生成）：`{s}` with `{circ}`。\n//
// 无 GUI 版本：`editor()` 返回 None。要做界面，加 `gui` feature 并在
// 手写的 `src/editor.rs` 里提供 `make(params, activity)`。
\n"
    ));
    out.push_str("use nih_plug::prelude::*;\n");
    out.push_str(&format!(
        "use {}::{};\n",
        m.circuit_crate(),
        m.circuit.plugin_type
    ));
    out.push_str("use rustomp_dsp::Engine;\n");
    out.push_str("use std::sync::{\n    atomic::{AtomicU32, Ordering},\n    Arc,\n};\n\n");
    out.push_str("use crate::generated::identity::*;\n");
    out.push_str("use crate::generated::params::PluginParams;\n\n");

    // 声道布局
    out.push_str(
        "#[cfg(all(feature = \"mono\", feature = \"stereo\"))]\n\
         compile_error!(\"mono 与 stereo 两个 feature 不能同时开启\");\n\n\
         #[cfg(feature = \"mono\")]\n\
         const AUDIO_LAYOUTS: &[AudioIOLayout] = &[AudioIOLayout {\n\
             main_input_channels: NonZeroU32::new(1),\n\
             main_output_channels: NonZeroU32::new(1),\n\
             aux_input_ports: &[],\n\
             aux_output_ports: &[],\n\
             names: PortNames::const_default(),\n\
         }];\n\n\
         #[cfg(feature = \"stereo\")]\n\
         const AUDIO_LAYOUTS: &[AudioIOLayout] = &[AudioIOLayout {\n\
             main_input_channels: NonZeroU32::new(2),\n\
             main_output_channels: NonZeroU32::new(2),\n\
             aux_input_ports: &[],\n\
             aux_output_ports: &[],\n\
             names: PortNames::const_default(),\n\
         }];\n\n\
         #[cfg(not(any(feature = \"mono\", feature = \"stereo\")))]\n\
         const AUDIO_LAYOUTS: &[AudioIOLayout] = &[\n\
             AudioIOLayout {\n\
                 main_input_channels: NonZeroU32::new(2),\n\
                 main_output_channels: NonZeroU32::new(2),\n\
                 aux_input_ports: &[],\n\
                 aux_output_ports: &[],\n\
                 names: PortNames::const_default(),\n\
             },\n\
             AudioIOLayout {\n\
                 main_input_channels: NonZeroU32::new(1),\n\
                 main_output_channels: NonZeroU32::new(1),\n\
                 ..AudioIOLayout::const_default()\n\
             },\n\
         ];\n\n",
    );

    // 结构体
    out.push_str(&format!(
        "/// 立体声上限；单声道变体只用第一路。\n\
         const MAX_CHANNELS: usize = 2;\n\n\
         pub struct {s} {{\n\
             params: Arc<PluginParams>,\n\
             engines: [Engine<{circ}>; MAX_CHANNELS],\n\
             /// 活动指示（0..1），GUI 读；原子存 f32 位，音频线程不加锁\n\
             activity: Arc<AtomicU32>,\n\
         }}\n\n\
         impl Default for {s} {{\n\
             fn default() -> Self {{\n\
                 Self {{\n\
                     params: Arc::new(PluginParams::default()),\n\
                     engines: std::array::from_fn(|_| Engine::<{circ}>::new(48_000.0)),\n\
                     activity: Arc::new(AtomicU32::new(0)),\n\
                 }}\n\
             }}\n\
         }}\n\n"
    ));

    // `bypass` 参数存在时，每个 buffer 开头同步给引擎
    let bypass_stmt = if m.params.iter().any(|p| p.id == "bypass") {
        "let bypass = self.params.bypass.value();\n                 for e in self.engines.iter_mut() { e.set_bypass(bypass); }"
    } else {
        "// （未声明 bypass 参数）"
    };

    // Plugin impl
    out.push_str(&format!(
        "impl Plugin for {s} {{\n\
             const NAME: &'static str = META_NAME;\n\
             const VENDOR: &'static str = META_VENDOR;\n\
             const URL: &'static str = META_URL;\n\
             const EMAIL: &'static str = META_EMAIL;\n\
             const VERSION: &'static str = env!(\"CARGO_PKG_VERSION\");\n\
             const AUDIO_IO_LAYOUTS: &'static [AudioIOLayout] = AUDIO_LAYOUTS;\n\
             const MIDI_INPUT: MidiConfig = MidiConfig::None;\n\
             const SAMPLE_ACCURATE_AUTOMATION: bool = false;\n\n\
             type SysExMessage = ();\n\
             type BackgroundTask = ();\n\n\
             fn params(&self) -> Arc<dyn Params> {{\n\
                 self.params.clone()\n\
             }}\n\n\
             fn initialize(\n\
                 &mut self,\n\
                 _layout: &AudioIOLayout,\n\
                 buffer_config: &BufferConfig,\n\
                 context: &mut impl InitContext<Self>,\n\
             ) -> bool {{\n\
                 let fs = buffer_config.sample_rate as f64;\n\
                 for e in self.engines.iter_mut() {{\n\
                     e.set_sample_rate(fs);\n\
                 }}\n\
                 context.set_latency_samples(Engine::<{circ}>::latency_samples());\n\
                 true\n\
             }}\n\n\
             fn reset(&mut self) {{\n\
                 for e in self.engines.iter_mut() {{\n\
                     e.reset();\n\
                 }}\n\
                 self.activity.store(0, Ordering::Relaxed);\n\
             }}\n\n\
             fn process(\n\
                 &mut self,\n\
                 buffer: &mut Buffer,\n\
                 _aux: &mut AuxiliaryBuffers,\n\
                 _context: &mut impl ProcessContext<Self>,\n\
             ) -> ProcessStatus {{\n\
                 // `bypass` 是保留参数 id：交给引擎的 true-bypass（5 ms 淡化 + 干路对齐）\n\
                 {bypass_stmt}\n\
                 let mut peak = 0.0f32;\n\
                 for mut channel_samples in buffer.iter_samples() {{\n\
                     let p = self.params.to_dsp();\n\
                     for (ch, sample) in channel_samples.iter_mut().enumerate() {{\n\
                         if let Some(e) = self.engines.get_mut(ch) {{\n\
                             e.set_params(p);\n\
                             *sample = e.process(*sample as f64) as f32;\n\
                             peak = peak.max(e.activity_indicator());\n\
                         }}\n\
                     }}\n\
                 }}\n\
                 self.activity.store(peak.to_bits(), Ordering::Relaxed);\n\
                 ProcessStatus::Normal\n\
             }}\n\n\
             fn deactivate(&mut self) {{\n\
                 for e in self.engines.iter_mut() {{\n\
                     e.reset();\n\
                 }}\n\
             }}\n\n\
             fn editor(&mut self, _async_executor: AsyncExecutor<Self>) -> Option<Box<dyn Editor>> {{\n\
                 make_editor(self.params.clone(), self.activity.clone())\n\
             }}\n\
         }}\n\n"
    ));

    // GUI 钩子（手写 src/editor.rs，feature = "gui"）
    out.push_str(
        "// ---------------------------------------------------------------- 界面钩子\n\
         // 这一阶段（进 GUI 之前）没有界面：`gui` feature 关闭时返回 None。\n\
         // 要做界面时，在手写的 `src/editor.rs` 里提供\n\
         //   pub fn make(params: Arc<PluginParams>, activity: Arc<AtomicU32>) -> Option<Box<dyn Editor>>\n\
         // 并开启 `gui` feature。\n\
         #[cfg(feature = \"gui\")]\n\
         fn make_editor(\n\
             params: Arc<PluginParams>,\n\
             activity: Arc<AtomicU32>,\n\
         ) -> Option<Box<dyn Editor>> {\n\
             crate::editor::make(params, activity)\n\
         }\n\n\
         #[cfg(not(feature = \"gui\"))]\n\
         fn make_editor(\n\
             _params: Arc<PluginParams>,\n\
             _activity: Arc<AtomicU32>,\n\
         ) -> Option<Box<dyn Editor>> {\n\
             None\n\
         }\n\n",
    );

    // CLAP / VST3
    out.push_str(&format!(
        "impl ClapPlugin for {s} {{\n\
             const CLAP_ID: &'static str = META_CLAP_ID;\n\
             const CLAP_DESCRIPTION: Option<&'static str> = META_CLAP_DESCRIPTION;\n\
             const CLAP_MANUAL_URL: Option<&'static str> = Some(META_URL);\n\
             const CLAP_SUPPORT_URL: Option<&'static str> = None;\n\
             const CLAP_FEATURES: &'static [ClapFeature] = &[\n\
                 ClapFeature::AudioEffect,\n\
                 #[cfg(not(feature = \"mono\"))]\n\
                 ClapFeature::Stereo,\n\
                 #[cfg(not(feature = \"stereo\"))]\n\
                 ClapFeature::Mono,\n\
                 ClapFeature::Distortion,\n\
             ];\n\
         }}\n\n\
         impl Vst3Plugin for {s} {{\n\
             const VST3_CLASS_ID: [u8; 16] = META_VST3_ID;\n\
             const VST3_SUBCATEGORIES: &'static [Vst3SubCategory] =\n\
                 &[Vst3SubCategory::Fx, Vst3SubCategory::Distortion];\n\
         }}\n\n\
         // 注意：末尾分号必须保留（宏展开成 item）。保留后编译器会报一条
         // `semicolon_in_expressions_from_non_local_macros` 警告 —— 那来自
         // nih-plug 自己的宏卫生问题，不是生成代码的错，忽略即可。
         nih_export_clap!({s});\n\
         nih_export_vst3!({s});\n"
    ));
    out
}

